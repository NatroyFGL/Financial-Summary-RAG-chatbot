"""
Financial Document RAG pipeline.

Shared by the command-line chatbot (chatbot.py) and the web demo (app.py):
indexing -> RAG-Fusion retrieval -> semantic routing -> LLM router -> grounded answer with citations.
"""
from operator import itemgetter
import os
import time
import warnings

from dotenv import load_dotenv
from langchain_core._api import LangChainBetaWarning
from langchain_core.documents import Document
from langchain_core.load import dumps, loads
from langchain_core.output_parsers import StrOutputParser
from langchain_core.prompts import ChatPromptTemplate
from langchain_core.runnables import RunnableLambda, RunnablePassthrough
from langchain_community.utils.math import cosine_similarity
from langchain_community.vectorstores import FAISS
#from langchain_huggingface import HuggingFaceEmbeddings
from langchain_huggingface import ChatHuggingFace, HuggingFaceEndpoint
from langchain_openai import ChatOpenAI, OpenAIEmbeddings

warnings.filterwarnings("ignore", category=LangChainBetaWarning)  # dumps/loads used by RAG-Fusion are "beta"

#resolve papers/ and faiss_index/ relative to this file, no matter where it's launched from
BASE_DIR = os.path.dirname(os.path.abspath(__file__))
load_dotenv(os.path.join(BASE_DIR, ".env"))

#Pipeline config
CHUNK_SIZE = 1200
CHUNK_OVERLAP = 200
EMBEDDING_MODEL = "text-embedding-3-large"
LLM_MODEL = "gpt-4o-mini"
HF_MODEL = "Qwen/Qwen2.5-7B-Instruct"  # LLM router: open-source model for SUMMARY questions
TOP_K = 5
SCORE_THRESHOLD = 0.2
NUM_QUERIES = 4  # RAG-Fusion: number of generated search queries
PAPERS_DIR = os.path.join(BASE_DIR, "papers")
FAISS_INDEX_PATH = os.path.join(BASE_DIR, "faiss_index")  # MLOps: local path to persist vector store
OPENAI_TIMEOUT = 30  # seconds per OpenAI call
HF_TIMEOUT = 15  # give up on Hugging Face quickly so the OpenAI fallback can still answer in time

#logged to MLflow by chatbot.py
CONFIG = {
    "chunk_size": CHUNK_SIZE,
    "chunk_overlap": CHUNK_OVERLAP,
    "embedding_model": EMBEDDING_MODEL,
    "top_k": TOP_K,
    "score_threshold": SCORE_THRESHOLD,
    "num_queries": NUM_QUERIES,
    "llm_model": LLM_MODEL,
    "hf_model": HF_MODEL,
}

# FAISS returns squared L2 distance; OpenAI embeddings are unit length, so cosine similarity = 1 - d/2
def cosine_relevance(distance):
    return 1 - distance / 2

def source_name(doc):
    # file name of a chunk's PDF ("papers\\x.pdf" from an index built on Windows -> "x.pdf")
    return os.path.basename(doc.metadata.get("source", "unknown").replace("\\", "/"))

# OpenAI embeddings
embeddings = OpenAIEmbeddings(
    model=EMBEDDING_MODEL,
    timeout=OPENAI_TIMEOUT
)

'''HuggingFace embeddings (open-source alternative)
embeddings = HuggingFaceEmbeddings(model_name="all-MiniLM-L6-v2")'''

llm = ChatOpenAI(
    model=LLM_MODEL,
    temperature=0,
    timeout=OPENAI_TIMEOUT
)

# Open-source model via Hugging Face Inference API (needs HUGGINGFACEHUB_API_TOKEN in .env)
hf_llm = ChatHuggingFace(llm=HuggingFaceEndpoint(
    repo_id=HF_MODEL,
    task="text-generation",
    max_new_tokens=512,
    temperature=0.01,
    timeout=HF_TIMEOUT
))


# INDEXING

def build_vectorstore():
    """Load the PDFs in papers/, split them into chunks, embed them and save the FAISS index to disk"""
    # imported here so the web app (which ships with a pre-built index) doesn't need PyMuPDF
    from langchain_community.document_loaders import DirectoryLoader, PyMuPDFLoader
    from langchain_text_splitters import RecursiveCharacterTextSplitter

    print("Building FAISS index...")
    loader = DirectoryLoader(
        path=PAPERS_DIR,
        glob="**/*.pdf",
        loader_cls=PyMuPDFLoader,
        show_progress=True,
        use_multithreading=True
    )
    docs = loader.load()

    text_splitter = RecursiveCharacterTextSplitter(
        chunk_size=CHUNK_SIZE,
        chunk_overlap=CHUNK_OVERLAP,
        add_start_index=True,
        strip_whitespace=True,
    )
    splits = text_splitter.split_documents(docs)

    store = FAISS.from_documents(
        documents=splits,
        embedding=embeddings,
        relevance_score_fn=cosine_relevance
    )
    store.save_local(FAISS_INDEX_PATH)  # MLOps: persist to disk
    print(f"FAISS index saved to '{FAISS_INDEX_PATH}/'")
    return store

#load FAISS index from disk if it exists, otherwise do indexing (load PDFs, split, embed and save it)
if os.path.exists(FAISS_INDEX_PATH):
    print("Loading FAISS index from disk...")
    vectorstore = FAISS.load_local(
        FAISS_INDEX_PATH,
        embeddings,
        allow_dangerous_deserialization=True,  # safe: the index is generated by this repo
        relevance_score_fn=cosine_relevance
    )
else:
    vectorstore = build_vectorstore()

retriever = vectorstore.as_retriever(
    search_type='similarity_score_threshold',
    search_kwargs={'k': TOP_K, 'score_threshold': SCORE_THRESHOLD}
)

def index_summary():
    """Number of chunks per PDF in the index (shown on the web page)"""
    counts = {}
    for doc_id in vectorstore.index_to_docstore_id.values():
        name = source_name(vectorstore.docstore.search(doc_id))
        counts[name] = counts.get(name, 0) + 1
    return [{"file": name, "chunks": n} for name, n in sorted(counts.items())]


# RETRIEVAL (RAG-Fusion)

# Generate several search queries from the user's question
template = f"""You are a helpful assistant that generates multiple search queries based on a single input query about financial documents.
Generate multiple search queries related to: {{question}}
Output ({NUM_QUERIES} queries, one per line, no numbering):"""
prompt_rag_fusion = ChatPromptTemplate.from_template(template)

generate_queries = (
    prompt_rag_fusion
    | llm
    | StrOutputParser()
    | (lambda x: [q.strip() for q in x.split("\n") if q.strip()])
)

def reciprocal_rank_fusion(results: list[list], k=60):
    """Fuse the ranked lists from each query: every doc scores 1 / (rank + k) per list it appears in"""
    fused_scores = {}
    for docs in results:
        for rank, doc in enumerate(docs):
            doc_str = dumps(doc)
            fused_scores[doc_str] = fused_scores.get(doc_str, 0) + 1 / (rank + k)

    reranked = sorted(fused_scores.items(), key=lambda x: x[1], reverse=True)
    fused_docs = []
    for doc_str, score in reranked[:TOP_K]:
        doc = loads(doc_str, allowed_objects=[Document])
        doc.metadata["rrf_score"] = round(score, 4)  # keep the fused score so it can be shown/logged
        fused_docs.append(doc)
    return fused_docs

def format_docs(docs):
    # Tag each chunk with source:page so the LLM can cite it
    return "\n\n".join(
        f"[{source_name(d)}:{d.metadata.get('page', 0) + 1}]\n{d.page_content}"
        for d in docs
    )


# GENERATION (semantic routing + LLM router)

RULES = (
    "RULES:\n"
    "1) Use ONLY the provided context to answer.\n"
    "2) If the answer is not clearly contained in the context, say: "
    "\"I don't know based on the provided documents.\"\n"
    "3) Do NOT use outside knowledge, guessing, or web information.\n"
    "4) Cite sources by copying the exact [file:page] tag shown above the chunk you used, in parentheses.\n\n"
    "Context:\n{context}\n\n"
    "Question: {question}"
)

# Each route: a persona (embedded for routing) + the shared strict rules
metrics_persona = (
    "You are a precise financial analyst. You answer questions about specific numbers: "
    "revenue, profit, margins, EPS, cash flow, debt, ratios, growth rates and year-over-year changes. "
    "Quote exact figures with their units and periods, and show any calculation step by step.\n"
)

summary_persona = (
    "You are an experienced financial advisor who explains documents clearly. You answer questions about "
    "overall performance, strategy, risks, outlook, management commentary and key takeaways. "
    "Give a concise, well-structured summary in plain language.\n"
)

personas = {"METRICS": metrics_persona, "SUMMARY": summary_persona}
persona_embeddings = embeddings.embed_documents(list(personas.values()))

# LLM router: each route also picks a model. Numbers need OpenAI's accuracy; summaries go to the
# open-source model, falling back to OpenAI if Hugging Face is down, rate-limited or has no token
model_routes = {
    "METRICS": llm,
    "SUMMARY": hf_llm.with_fallbacks([llm]),
}

def router(input):
    # Semantic routing: pick the persona whose description is most similar to the question
    query_embedding = embeddings.embed_query(input["question"])
    similarity = cosine_similarity([query_embedding], persona_embeddings)[0]
    route = list(personas)[similarity.argmax()]
    print(f"Using {route}")
    return {"name": route, "scores": {name: round(float(s), 4) for name, s in zip(personas, similarity)}}

def generate(input):
    # LLM router: the chosen route's persona prompt + model (LangChain runs the returned chain on the same input)
    route = input["route"]["name"]
    return ChatPromptTemplate.from_template(personas[route] + RULES) | model_routes[route]

def answer_model(message):
    # Which model actually answered (shows when the fallback kicked in)
    return message.response_metadata.get("model_name") or message.response_metadata.get("model") or HF_MODEL

# Full pipeline. Each step adds its output to the dict, so the result keeps every intermediate step
# (generated queries, retrieved chunks, route) for MLflow logging and the web demo's "how it was found" view
final_rag_chain = (
    RunnablePassthrough.assign(                       # RAG-Fusion queries and semantic routing run in parallel
        queries=generate_queries,
        route=RunnableLambda(router),
    )
    | RunnablePassthrough.assign(docs=itemgetter("queries") | retriever.map() | reciprocal_rank_fusion)
    | RunnablePassthrough.assign(context=itemgetter("docs") | RunnableLambda(format_docs))
    | RunnablePassthrough.assign(message=RunnableLambda(generate))
)


def ask(question: str) -> dict:
    """Answer a question from the indexed PDFs and report what happened at each step"""
    start = time.perf_counter()
    result = final_rag_chain.invoke({"question": question})
    message = result["message"]
    route = result["route"]["name"]
    model = answer_model(message)
    print(f"Answered by {model}")

    planned_model = HF_MODEL if route == "SUMMARY" else LLM_MODEL
    return {
        "question": question,
        "answer": StrOutputParser().invoke(message),
        "route": route,
        "route_scores": result["route"]["scores"],
        "planned_model": planned_model,
        "answer_model": model,
        "fallback": planned_model == HF_MODEL and model.lower().startswith("gpt"),
        "queries": result["queries"],
        "sources": [
            {
                "file": source_name(d),
                "page": d.metadata.get("page", 0) + 1,
                "score": d.metadata.get("rrf_score"),
                "text": d.page_content,
            }
            for d in result["docs"]
        ],
        "seconds": round(time.perf_counter() - start, 2),
    }
